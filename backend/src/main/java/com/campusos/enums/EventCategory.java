package com.campusos.enums;

/**
 * Categories for campus events.
 *
 * TECHNICAL   — coding contests, tech talks, hackathons
 * CULTURAL    — music, dance, drama, art events
 * SPORTS      — tournaments, matches, fitness events
 * WORKSHOP    — hands-on learning sessions
 * SEMINAR     — lectures, guest speaker sessions
 * HACKATHON   — time-bound building competitions
 * COMPETITION — contests, quizzes, debates
 * CLUB        — general club-organised events
 * OTHER       — anything that doesn't fit above
 */
public enum EventCategory {
    TECHNICAL,
    CULTURAL,
    SPORTS,
    WORKSHOP,
    SEMINAR,
    HACKATHON,
    COMPETITION,
    CLUB,
    OTHER
}
